"""What the DEPLOYED shadow controller decided during a fault run (not a replay).

  python -m topo.live_decisions --events topo/results/run3_controller_boutique_events.jsonl \\
         --fault-log topo/boutique_fault_log_run3.jsonl --out topo/results/phase4_live_shadow_run3.md

`--events` holds the controller's own audit events (here exported from the fleet API's store). In shadow mode with no
playbook, a persistent alarm shows up as ACTION_BLOCKED (`no_healthy_alternative`): the controller decided to act on that
service and was stopped only by the missing remedy. Per episode: caught (an alarm on the faulted service between fault
start and the end of recovery), delay from fault start, and whether another service was alarmed first. Outside episodes
(phase "normal", away from every episode): false-alarm onsets per hour.
"""
import argparse
import collections
import json
import os
import sys
from datetime import timedelta

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)

from topo import real  # noqa: E402
from topo.persistence import _ts as _snap_ts  # noqa: E402

ONSET_GAP = timedelta(seconds=60)


def _ts(e):
    return _snap_ts({"timestamp": e["ts"]})


def analyse(events, eps, exclude=()):
    events = [e for e in events if not any(x <= _ts(e) <= y for x, y in exclude)]
    alarms = [e for e in events if e["event"] in ("ACTION_BLOCKED", "REROUTE")]
    scored = [e for e in events if e["event"] == "SCORED"]
    rows = []
    for ep in eps:
        lo, hi = ep["start"], ep["end"] + real.RECOVERY
        inside = [a for a in alarms if lo <= _ts(a) <= hi]
        hit = [a for a in inside if a.get("node") == ep["node"]]
        rows.append({"episode": ep["id"], "type": ep.get("type", "delay"), "node": ep["node"], "caught": bool(hit),
                     "delay_s": round((_ts(hit[0]) - lo).total_seconds()) if hit else None,
                     "first_alarm": inside[0]["node"] if inside else None,
                     "wrong_first": bool(inside) and inside[0].get("node") != ep["node"]})
    normal_alarms = [a for a in alarms if real.classify(_ts(a), eps)[0] == "normal"]
    onsets, last = [], None
    for a in normal_alarms:
        if last is None or _ts(a) - _ts(last) > ONSET_GAP or a.get("node") != last.get("node"):
            onsets.append(a)
        last = a
    normal_hours = sum(1 for s in scored if real.classify(_ts(s), eps)[0] == "normal") * 15 / 3600
    return rows, onsets, normal_hours


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--events", required=True)
    ap.add_argument("--fault-log", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--exclude", nargs=2, action="append", default=[], metavar=("FROM", "TO"),
                    help="ignore events in this ISO time window (UTC), e.g. an unlogged partial episode; repeatable")
    a = ap.parse_args(argv)
    events = sorted(real.load_jsonl(a.events), key=_ts)
    eps = real.load_episodes(a.fault_log)
    exclude = [(_snap_ts({"timestamp": x}), _snap_ts({"timestamp": y})) for x, y in a.exclude]
    rows, onsets, hours = analyse(events, eps, exclude)
    by = collections.defaultdict(list)
    for r in rows:
        by[r["type"]].append(r)
    lines = ["# Deployed shadow controller during the run (generated by topo/live_decisions.py)", "",
             f"{len(events)} controller events from {events[0]['ts']} to {events[-1]['ts']}; {len(eps)} episodes. "
             "Persistent alarm = ACTION_BLOCKED or REROUTE for that service."
             + (" Excluded windows: " + "; ".join(f"{x} to {y}" for x, y in a.exclude) + "." if a.exclude else ""), "",
             "| fault type | caught | wrong service first | median delay |", "|---|---|---|---|"]
    for t, rs in sorted(by.items()):
        d = sorted(r["delay_s"] for r in rs if r["caught"])
        med = f"{d[len(d) // 2]} s" if d else "n/a"
        lines.append(f"| {t} | {sum(r['caught'] for r in rs)}/{len(rs)} | {sum(r['wrong_first'] for r in rs)} | {med} |")
    lines += ["", f"Fault-free time away from episodes: {hours:.2f} h, {len(onsets)} false-alarm onsets "
              f"({len(onsets) / hours:.2f} per hour)" if hours else "", ""]
    if onsets:
        lines += ["False-alarm onsets: " + ", ".join(f"{o['ts'][11:19]} {o.get('node')}" for o in onsets), ""]
    lines += ["| episode | type | service | caught | after s | first alarm |", "|---|---|---|---|---|---|"]
    lines += [f"| {r['episode']} | {r['type']} | {r['node']} | {'yes' if r['caught'] else 'no'} | "
              f"{r['delay_s'] if r['delay_s'] is not None else '-'} | {r['first_alarm'] or '-'} |" for r in rows]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
