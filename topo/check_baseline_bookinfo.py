"""Independent check of the learned BaselineScorer on real Bookinfo (the design was iterated on Online Boutique, so
Bookinfo is the data it was NOT shaped on).

Split, as in the original Bookinfo evaluation (build_dataset_v2): the holdout is the latest 25% of pure-normal
snapshots. The baseline is learned from the OTHER normal snapshots only; the test set is every steady fault snapshot
plus the holdout normals. Lag and recovery snapshots are excluded everywhere.

  python -m topo.check_baseline_bookinfo --tag phase4_baseline_bookinfo
"""
import argparse
import os
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "meshheal_controlplane"))

from controlplane import learn_baseline as lb  # noqa: E402
from topo import eval as ev  # noqa: E402


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--quantile", type=float, default=0.99)
    ap.add_argument("--floor-ms", type=float, default=10.0)
    ap.add_argument("--exclude-v3", action="store_true",
                    help="drop the noisy windows of excluded_windows_v3.json (REPORT_V3, 2026-10-27) from learn and test")
    a = ap.parse_args(argv)
    out = os.path.join(ROOT, "topo", "results", a.tag + ".md")
    if os.path.exists(out):
        raise SystemExit(f"refusing to overwrite {out}")

    cwd = os.getcwd()
    os.chdir(ROOT)
    try:
        from build_dataset_v2 import build_normal_holdout_ts, load_all_records
        recs = load_all_records()
        holdout = build_normal_holdout_ts(recs)
    finally:
        os.chdir(cwd)
    excluded = set()
    if a.exclude_v3:
        import json
        from datetime import datetime
        wins = [(datetime.fromisoformat(w["start"]), datetime.fromisoformat(w["end"]))
                for w in json.load(open(os.path.join(ROOT, "excluded_windows_v3.json"), encoding="utf-8"))["windows"]]
        excluded = {r["timestamp"] for r in recs
                    if any(s <= datetime.fromisoformat(r["timestamp"]) <= e for s, e in wins)}
    learn = [r for r in recs if r["phase"] == "normal" and r["timestamp"] not in holdout and r["timestamp"] not in excluded]
    test = [r for r in recs if (r["phase"] == "steady" or (r["phase"] == "normal" and r["timestamp"] in holdout))
            and r["timestamp"] not in excluded]
    for r in test:
        r["topology"], r["family"] = "bookinfo-real", "real"

    base, notes = lb.build_baseline(lb.collect_normal_stats(learn), q=a.quantile)
    edges, _ = lb.build_edges(lb.collect_normal_edges(learn), q=a.quantile)
    import yaml
    with tempfile.TemporaryDirectory() as t:
        path = os.path.join(t, "bookinfo_baseline.yaml")
        with open(path, "w", encoding="utf-8") as f:
            yaml.safe_dump({"method": f"envelope-q{a.quantile}", "floor_ms": a.floor_ms, "min_rate": 0.05, "services": base, "edges": edges}, f)
        graphs = ev.build_graphs(test, path)

    n_st = sum(1 for g in graphs if g.phase == "steady")
    lines = [f"# Learned baseline on real Bookinfo (independent check; generated by topo/check_baseline_bookinfo.py)", "",
             f"Learned from {len(learn)} normal snapshots (not the holdout). Test: {len(graphs)} snapshots = {n_st} steady fault "
             f"snapshots (8 episodes) + {len(graphs) - n_st} holdout normals. Envelope q{a.quantile}, floor {a.floor_ms} ms.",
             "The baseline design was iterated on Online Boutique, not on this data.",
             (f"REPORT_V3's noisy windows (excluded_windows_v3.json, fixed on 2026-10-27) are EXCLUDED: {len(excluded)} snapshots."
              if a.exclude_v3 else "REPORT_V3's noisy windows are INCLUDED (the holdout contains window B1, labelled normal but elevated)."), "",
             "| scorer | AP | RC@1 | FPR@0.85 |", "|---|---|---|---|"]
    for name in ("edge", "baseline", "baseline_clamp", "rule", "p95"):
        m = ev.evaluate(graphs, ev.baseline_scores(name, graphs), risk_scale=(name in ev.RISK_SCALED))
        fpr = "n/a" if m["fpr"] != m["fpr"] else f"{m['fpr']:.3f}"
        lines.append(f"| {name} | {m['ap']:.3f} | {m['rc1']:.3f} | {fpr} |")
    lines += ["", "Learned services: " + ", ".join(f"{k} (median {v['in_lat']['median']:.1f}, high {v['in_lat']['high']:.1f} ms)"
                                                  for k, v in base.items())]
    if notes:
        lines += ["", "Notes: " + "; ".join(notes)]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
